// Writes the shared CSS into a component's stylesheet: a template from src/styles/, with its placeholder names replaced
// by the component's, between two marker comments in the component's src/*.css. The result is committed, so the
// stylesheet stays complete plain CSS, with no @import and no build. A component's tools/sync-css.mjs calls syncCss()
// with its names:
//
//   node tools/sync-css.mjs             (or npm run sync:css)     rewrites the region
//   node tools/sync-css.mjs --check     (or npm run check:css)    changes nothing; fails if the region differs
//
// The component places the two markers itself, once, where the shared rules go (inside its @supports, before its own
// rules), each on a line of its own; the tool writes what's between them, at the first one's indentation:
//
//   /* Burrowkit popover.css begin */
//   /* Burrowkit popover.css end */
//
// The first marker is rewritten to say which version of Burrowkit the region is from, so a region from another version
// differs even if its rules don't. Edits inside the region are lost on the next sync.
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

/**
 * Syncs the region of `root`/src/`css`. `host` is the component's element, `prefix` its class prefix (without the
 * hyphen), `name` what its public variables, highlight, keyframes and @position-try are named after, `template` the
 * file in Burrowkit's src/styles/. `args` are the command line's arguments. Sets process.exitCode when --check finds a
 * difference.
 */
export async function syncCss({ root, css, host, prefix, name, template = "popover.css", args = process.argv.slice(2) }) {
    const unknown = args.filter(arg => arg !== "--check");
    if (unknown.length) throw new Error(`Unknown argument ${unknown[0]}; the only one is --check.`);
    const check = args.includes("--check");

    // A setting left out would be written into the stylesheet as "undefined".
    const missing = Object.entries({ root, css, host, prefix, name })
        .find(([, value]) => typeof value !== "string" || !value);
    if (missing) throw new Error(`syncCss() needs ${missing[0]}.`);

    const { version } = JSON.parse(await readFile(new URL("../package.json", import.meta.url), "utf8"));
    const source = await readFile(new URL(`../src/styles/${template}`, import.meta.url), "utf8");

    const shared = source
        .replace(/\r\n/g, "\n")
        .replace(/^\/\*[\s\S]*?\*\/\n/, "")  // The template's own comment.
        .trim()
        // Whole names only. In .bk-x and --_bk-x the prefix follows a dot or an underscore.
        .replace(/(?<![\w-])burrow-host(?![\w-])/g, () => host)
        .replace(/(?<![A-Za-z0-9])bk-/g, () => `${prefix}-`)
        .replace(/(?<![A-Za-z0-9])burrowkit(?![A-Za-z0-9_])/g, () => name);

    const path = join(root, "src", css);
    const file = await readFile(path, "utf8");
    const eol = file.includes("\r\n") ? "\r\n" : "\n";
    const lines = file.split(/\r?\n/);

    const marker = `Burrowkit ${template}`;
    const find = word => {
        const found = lines.flatMap((line, at) => line.trim().startsWith(`/* ${marker} ${word}`) ? [at] : []);
        if (found.length !== 1) {
            throw new Error(`src/${css} needs one line "/* ${marker} ${word} */", and has ${found.length}.`);
        }
        return found[0];
    };
    const begin = find("begin");
    const end = find("end");
    if (end < begin) throw new Error(`src/${css}: the end marker of ${template} comes before the begin marker.`);

    const indent = lines[begin].match(/^[ \t]*/)[0];
    const region = [
        `/* ${marker} begin (burrowkit ${version}). Generated by npm run sync:css: don't edit, it's overwritten. */`,
        ...shared.split("\n"),
        `/* ${marker} end */`,
    ].map(line => line && indent + line);

    const current = lines.slice(begin, end + 1);
    const same = current.join("\n") === region.join("\n");

    if (same) {
        console.log(`src/${css}: ${template} is up to date (burrowkit ${version}).`);
    } else if (check) {
        const at = region.findIndex((line, i) => line !== current[i]);
        console.error(`src/${css}: ${template} differs from burrowkit ${version}'s, first at line ${begin + (at < 0 ? region.length : at) + 1}. Run npm run sync:css.`);
        process.exitCode = 1;
    } else {
        lines.splice(begin, current.length, ...region);
        await writeFile(path, lines.join(eol));
        console.log(`src/${css}: wrote ${template} from burrowkit ${version}.`);
    }
}